void create_screen_launcher() {
    void *flowState = getFlowState(0, 0);
    (void)flowState;
    lv_obj_t *obj = lv_obj_create(0);
    objects.launcher = obj;
    lv_obj_set_pos(obj, 0, 0);
    lv_obj_set_size(obj, 240, 320);
    {
        lv_obj_t *parent_obj = obj;
        {
            // label
            lv_obj_t *obj = lv_label_create(parent_obj);
            objects.label = obj;
            lv_obj_set_pos(obj, 80, 103);
            lv_obj_set_size(obj, LV_SIZE_CONTENT, LV_SIZE_CONTENT);
            lv_label_set_text_static(obj, "hello world");
        }
        {
            lv_obj_t *obj = lv_btn_create(parent_obj);
            objects.obj0 = obj;
            lv_obj_set_pos(obj, 70, 199);
            lv_obj_set_size(obj, 102, 50);
            lv_obj_add_event_cb(obj, event_handler_cb_launcher_obj0, LV_EVENT_ALL, flowState);
            lv_obj_set_scrollbar_mode(obj, LV_SCROLLBAR_MODE_OFF);
            lv_obj_set_scroll_dir(obj, LV_DIR_NONE);
            lv_obj_set_scroll_snap_x(obj, LV_SCROLL_SNAP_NONE);
            lv_obj_set_scroll_snap_y(obj, LV_SCROLL_SNAP_NONE);
            {
                lv_obj_t *parent_obj = obj;
                {
                    // btn
                    lv_obj_t *obj = lv_label_create(parent_obj);
                    objects.btn = obj;
                    lv_obj_set_pos(obj, 0, 0);
                    lv_obj_set_size(obj, LV_SIZE_CONTENT, LV_SIZE_CONTENT);
                    lv_obj_set_style_align(obj, LV_ALIGN_CENTER, LV_PART_MAIN | LV_STATE_DEFAULT);
                    lv_label_set_text_static(obj, "click me");
                }
            }
        }
    }
    
    tick_screen_launcher();
}

void delete_screen_launcher() {
    lv_obj_del(objects.launcher);
    objects.launcher = 0;
    objects.label = 0;
    objects.obj0 = 0;
    objects.btn = 0;
    deletePageFlowState(0);
}

void tick_screen_launcher() {
    void *flowState = getFlowState(0, 0);
    (void)flowState;
}

